import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const BACKEND = resolve(__dirname, "..");

function parseEnv(content) {
  const env = {};
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  }
  return env;
}

function quoteIfNeeded(value) {
  if (/[\s#"'@!]/.test(value)) return `"${value.replace(/"/g, '\\"')}"`;
  return value;
}

function serializeEnv(env, order) {
  const lines = [
    "# Simba Academy API — cPanel production (generated by prepare-cpanel-env.mjs)",
    "",
  ];
  const written = new Set();
  for (const key of order) {
    if (env[key] === undefined) continue;
    lines.push(`${key}=${quoteIfNeeded(env[key])}`);
    written.add(key);
  }
  const rest = Object.keys(env)
    .filter((k) => !written.has(k) && !k.startsWith("CPANEL_"))
    .sort();
  if (rest.length) {
    lines.push("");
    for (const key of rest) {
      lines.push(`${key}=${quoteIfNeeded(env[key])}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

